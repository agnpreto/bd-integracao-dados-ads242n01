-- 01_ddl_postgres.sql
-- DDL corrigido para PostgreSQL (testado no PostgreSQL 16)
-- Autor: João Gustavo Gonçalves Vasconcelos (2408298)
--
-- Principais correções em relação a sql/01_ddl_enunciado.sql (detalhes em docs/parte1_importacao.md):
--  * entradas_mercadoria: a coluna ordem_compra não existia, mas estava na PK -> coluna criada.
--  * produtos_filial: faltava vírgula antes da CONSTRAINT; PK usava "idproduto" (a coluna é produto_id);
--    "decricao" e "idfonecedor" corrigidos para "descricao" e "idfornecedor".
--  * fornecedor: "idforncedor" -> "idfornecedor"; a PK não pode usar "idproduto" (a coluna não existe e
--    fornecedor não tem produto).
--  * Chaves estrangeiras criadas (antes não havia nenhuma relação entre as tabelas).
--  * Tipos corrigidos: ids e quantidades inteiras como INTEGER/BIGINT em vez de float8;
--    valores monetários e quantidades fracionadas como NUMERIC em vez de float8.
--  * idfornecedor passou a ser numérico (o enunciado pede "idfornecedor numérico" e
--    pedido_compra.fornecedor_id já era int4); na planilha 'F8' vira 8.

DROP TABLE IF EXISTS public.venda CASCADE;
DROP TABLE IF EXISTS public.entradas_mercadoria CASCADE;
DROP TABLE IF EXISTS public.pedido_compra CASCADE;
DROP TABLE IF EXISTS public.produtos_filial CASCADE;
DROP TABLE IF EXISTS public.fornecedor CASCADE;

CREATE TABLE public.fornecedor (
    idfornecedor  integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    razao_social  varchar(255) NOT NULL,
    CONSTRAINT fornecedor_pkey PRIMARY KEY (idfornecedor)
);

CREATE TABLE public.produtos_filial (
    filial_id       int4          NOT NULL,
    produto_id      varchar(25)   NOT NULL,
    descricao       varchar(255)  NOT NULL,
    estoque         numeric(14,3) DEFAULT 0 NOT NULL,
    preco_unitario  numeric(12,4) DEFAULT 0 NOT NULL,
    preco_compra    numeric(12,4) DEFAULT 0 NOT NULL,
    preco_venda     numeric(12,4) DEFAULT 0 NOT NULL,
    idfornecedor    int4          NULL,
    CONSTRAINT produtos_filial_pkey PRIMARY KEY (filial_id, produto_id),
    CONSTRAINT fk_produtos_fornecedor FOREIGN KEY (idfornecedor)
        REFERENCES public.fornecedor (idfornecedor)
);

CREATE TABLE public.pedido_compra (
    pedido_id          int8          DEFAULT 0 NOT NULL,
    data_pedido        date          NULL,
    item               int4          DEFAULT 0 NOT NULL,
    produto_id         varchar(25)   DEFAULT '0' NOT NULL,
    descricao_produto  varchar(255)  NULL,
    ordem_compra       int8          DEFAULT 0 NOT NULL,
    qtde_pedida        numeric(14,3) NULL,
    filial_id          int4          NULL,
    data_entrega       date          NULL,
    qtde_entregue      numeric(14,3) DEFAULT 0 NOT NULL,
    qtde_pendente      numeric(14,3) DEFAULT 0 NOT NULL,
    preco_compra       numeric(12,4) DEFAULT 0 NULL,
    fornecedor_id      int4          DEFAULT 0 NULL,
    CONSTRAINT pedido_compra_pkey PRIMARY KEY (pedido_id, produto_id, item)
);
-- Observação: fornecedor_id fica sem FK, porque o DEFAULT 0 do enunciado não existe em fornecedor.
-- A integridade é verificada em sql/04_validacao.sql. Também não há FK para produtos_filial porque
-- existem pedidos de produtos fora do cadastro (ver Parte 4).

CREATE TABLE public.entradas_mercadoria (
    data_entrada       date          NULL,
    nro_nfe            varchar(255)  NOT NULL,
    item               int4          DEFAULT 0 NOT NULL,
    produto_id         varchar(25)   DEFAULT '0' NOT NULL,
    descricao_produto  varchar(255)  NULL,
    ordem_compra       int8          DEFAULT 0 NOT NULL,   -- coluna que faltava no DDL do enunciado
    qtde_recebida      numeric(14,3) NULL,
    filial_id          int4          NULL,
    custo_unitario     numeric(12,4) DEFAULT 0 NOT NULL,
    CONSTRAINT entradas_mercadoria_pkey PRIMARY KEY (ordem_compra, item, produto_id, nro_nfe)
);

CREATE TABLE public.venda (
    venda_id        int8          NOT NULL,
    data_emissao    date          NOT NULL,
    horariomov      varchar(8)    DEFAULT '00:00:00' NOT NULL,
    produto_id      varchar(25)   DEFAULT '' NOT NULL,
    qtde_vendida    numeric(14,3) NULL,
    valor_unitario  numeric(12,4) DEFAULT 0 NOT NULL,
    filial_id       int8          DEFAULT 1 NOT NULL,
    item            int4          DEFAULT 0 NOT NULL,
    unidade_medida  varchar(3)    NULL,
    CONSTRAINT pk_venda PRIMARY KEY (filial_id, venda_id, data_emissao, produto_id, item, horariomov)
);

CREATE INDEX idx_venda_data       ON public.venda (data_emissao);
CREATE INDEX idx_pedido_ordem     ON public.pedido_compra (ordem_compra);
CREATE INDEX idx_entradas_ordem   ON public.entradas_mercadoria (ordem_compra);
