-- DDL corrigido para PostgreSQL (testado no PostgreSQL 16)
-- Nome: Mateus Farias Bentes
--
-- Resumo das decisões (detalhes em docs/parte1_importacao.md):
--   * Corrigidos os erros que impediam a criação (vírgula faltando, colunas
--     inexistentes nas PKs, nomes com erro de digitação).
--   * Identificadores (pedido_id, item, ordem_compra) passam de float8 para integer:
--     chave com ponto flutuante pode dar 1.0000001 <> 1 e não faz sentido ter "meio pedido".
--   * Quantidades e valores em numeric (exato). float8 gera erro de arredondamento em soma de R$.
--   * fornecedor.idfornecedor passa a ser NUMÉRICO (F1 -> 1). Motivo: pedido_compra.fornecedor_id
--     já vem numérico na planilha e a Parte 3 pede um idfornecedor numérico. O código original
--     ('F1') fica guardado em codigo_origem para rastreabilidade.
--   * Criadas as chaves estrangeiras que os dados suportam. venda -> produtos_filial NÃO tem FK
--     porque a planilha tem vendas de produtos não cadastrados (P21..P28); preferimos importar
--     tudo e apontar o problema na validação (Parte 4) do que perder linhas.
--   * qtde_pendente virou coluna calculada: nunca fica inconsistente com pedida - entregue.

DROP TABLE IF EXISTS public.venda CASCADE;
DROP TABLE IF EXISTS public.entradas_mercadoria CASCADE;
DROP TABLE IF EXISTS public.pedido_compra CASCADE;
DROP TABLE IF EXISTS public.produtos_filial CASCADE;
DROP TABLE IF EXISTS public.fornecedor CASCADE;

-- ─────────────────────────────────────────────────────────────
-- FORNECEDOR
-- Erro original: coluna "idforncedor" (digitação) e PK com "idproduto", que não existe.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE public.fornecedor (
    idfornecedor  integer GENERATED BY DEFAULT AS IDENTITY,
    codigo_origem varchar(25)  NULL,          -- código como veio do cliente: 'F1', 'F2'...
    razao_social  varchar(255) NOT NULL,
    CONSTRAINT fornecedor_pkey PRIMARY KEY (idfornecedor),
    CONSTRAINT fornecedor_codigo_uk UNIQUE (codigo_origem)
);

-- ─────────────────────────────────────────────────────────────
-- PRODUTOS_FILIAL
-- Erros originais: falta vírgula antes de CONSTRAINT; PK com "idproduto" (coluna se chama
-- produto_id); "decricao" e "idfonecedor" com erro de digitação; filial_id NULL mas na PK.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE public.produtos_filial (
    filial_id      integer       NOT NULL,
    produto_id     varchar(25)   NOT NULL,     -- 25 para casar com as outras tabelas
    descricao      varchar(255)  NOT NULL,
    estoque        numeric(14,3) DEFAULT 0 NOT NULL,
    preco_unitario numeric(12,4) DEFAULT 0 NOT NULL,
    preco_compra   numeric(12,4) DEFAULT 0 NOT NULL,
    preco_venda    numeric(12,4) DEFAULT 0 NOT NULL,
    idfornecedor   integer       NULL,
    CONSTRAINT produtos_filial_pkey PRIMARY KEY (filial_id, produto_id),
    CONSTRAINT produtos_filial_fornecedor_fk FOREIGN KEY (idfornecedor)
        REFERENCES public.fornecedor (idfornecedor),
    CONSTRAINT produtos_filial_precos_ck CHECK (preco_unitario >= 0 AND preco_compra >= 0 AND preco_venda >= 0)
);

-- ─────────────────────────────────────────────────────────────
-- PEDIDO_COMPRA
-- DDL original criava, mas com tipos ruins (float8 em chave) e sem relação com fornecedor.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE public.pedido_compra (
    pedido_id         integer       NOT NULL,
    data_pedido       date          NULL,
    item              integer       DEFAULT 0 NOT NULL,
    produto_id        varchar(25)   NOT NULL,
    descricao_produto varchar(255)  NULL,
    ordem_compra      integer       DEFAULT 0 NOT NULL,   -- 0 = pedido sem ordem de compra
    qtde_pedida       numeric(14,3) NULL,
    filial_id         integer       NULL,
    data_entrega      date          NULL,
    qtde_entregue     numeric(14,3) DEFAULT 0 NOT NULL,
    qtde_pendente     numeric(14,3) GENERATED ALWAYS AS (COALESCE(qtde_pedida, 0) - qtde_entregue) STORED,
    preco_compra      numeric(12,4) DEFAULT 0 NULL,
    fornecedor_id     integer       NULL,
    CONSTRAINT pedido_compra_pkey PRIMARY KEY (pedido_id, produto_id, item),
    CONSTRAINT pedido_compra_fornecedor_fk FOREIGN KEY (fornecedor_id)
        REFERENCES public.fornecedor (idfornecedor)
);
CREATE INDEX pedido_compra_ordem_idx ON public.pedido_compra (ordem_compra);

-- ─────────────────────────────────────────────────────────────
-- ENTRADAS_MERCADORIA
-- Erro original: a PK usa ordem_compra, mas a coluna não foi declarada.
-- Ela é justamente o vínculo com pedido_compra (ver README).
-- ─────────────────────────────────────────────────────────────
CREATE TABLE public.entradas_mercadoria (
    data_entrada      date          NULL,
    nro_nfe           varchar(255)  NOT NULL,
    item              integer       DEFAULT 0 NOT NULL,
    produto_id        varchar(25)   NOT NULL,
    descricao_produto varchar(255)  NULL,
    ordem_compra      integer       NOT NULL,
    qtde_recebida     numeric(14,3) NULL,
    filial_id         integer       NULL,
    custo_unitario    numeric(12,4) DEFAULT 0 NOT NULL,
    CONSTRAINT entradas_mercadoria_pkey PRIMARY KEY (ordem_compra, item, produto_id, nro_nfe)
);

-- ─────────────────────────────────────────────────────────────
-- VENDA
-- Criava no PostgreSQL, mas: horariomov como texto (virou time), qtde em float8,
-- filial_id int8 (inconsistente com int4 nas outras tabelas) e o nome da PK "pk_consumo".
-- ─────────────────────────────────────────────────────────────
CREATE TABLE public.venda (
    venda_id       bigint        NOT NULL,
    data_emissao   date          NOT NULL,
    horariomov     time          DEFAULT '00:00:00' NOT NULL,
    produto_id     varchar(25)   NOT NULL,
    qtde_vendida   numeric(14,3) NULL,
    valor_unitario numeric(12,4) DEFAULT 0 NOT NULL,
    filial_id      integer       DEFAULT 1 NOT NULL,
    item           integer       DEFAULT 0 NOT NULL,
    unidade_medida varchar(3)    NULL,
    CONSTRAINT venda_pkey PRIMARY KEY (filial_id, venda_id, data_emissao, produto_id, item, horariomov)
);
CREATE INDEX venda_data_idx    ON public.venda (data_emissao);
CREATE INDEX venda_produto_idx ON public.venda (produto_id);
