-- DDL corrigido para PostgreSQL (10 ou superior, por causa do IDENTITY)
-- Origem: sql/01_ddl_enunciado.sql. Cada correcao esta explicada em
-- docs/parte1_importacao.md (secao "Erros encontrados no DDL").
--
-- Como executar:
--   createdb -U postgres base_teste
--   psql -U postgres -d base_teste -f sql/01_ddl_postgres.sql
--
-- Decisoes de modelagem:
--   1. Os ids de fornecedor passam a ser INTEGER em todas as tabelas. Na
--      planilha eles chegam como 'F1'..'F20' na aba fornecedor/produtos_filial
--      e como 1..20 na aba pedido_compra; o script de importacao normaliza.
--   2. fornecedor.idfornecedor e uma identidade que comeca em 21: a carga grava
--      os ids 1..20 explicitamente e a trigger da Parte 3 gera os proximos.
--   3. Foram criadas FKs so onde os dados permitem. venda.produto_id e
--      entradas_mercadoria.ordem_compra ficaram SEM FK porque a base de teste
--      tem vendas de produtos nao cadastrados (P21..P28) e entradas de ordens
--      inexistentes (19 e 20). Esses casos sao listados em sql/04_validacao.sql.

DROP TABLE IF EXISTS public.venda CASCADE;
DROP TABLE IF EXISTS public.entradas_mercadoria CASCADE;
DROP TABLE IF EXISTS public.pedido_compra CASCADE;
DROP TABLE IF EXISTS public.produtos_filial CASCADE;
DROP TABLE IF EXISTS public.fornecedor CASCADE;

-- Fornecedor: PK so pelo id (o original tinha 'idforncedor' e citava
-- 'idproduto', coluna que nao existe nesta tabela).
CREATE TABLE public.fornecedor (
    idfornecedor integer GENERATED BY DEFAULT AS IDENTITY (START WITH 21),
    razao_social varchar(255) NOT NULL,
    CONSTRAINT fornecedor_pkey PRIMARY KEY (idfornecedor)
);

-- Produtos por filial: corrigidos 'decricao', 'idfonecedor', a virgula que
-- faltava antes do CONSTRAINT e a PK que citava 'idproduto'.
CREATE TABLE public.produtos_filial (
    filial_id      integer          NOT NULL,
    produto_id     varchar(25)      NOT NULL,
    descricao      varchar(255)     NOT NULL,
    estoque        double precision NOT NULL DEFAULT 0,
    preco_unitario double precision NOT NULL DEFAULT 0,
    preco_compra   double precision NOT NULL DEFAULT 0,
    preco_venda    double precision NOT NULL DEFAULT 0,
    idfornecedor   integer          NULL,
    CONSTRAINT produtos_filial_pkey PRIMARY KEY (filial_id, produto_id),
    CONSTRAINT produtos_filial_fornecedor_fk
        FOREIGN KEY (idfornecedor) REFERENCES public.fornecedor (idfornecedor)
);

-- Pedido de compra: ids e item deixam de ser float8 e fornecedor_id deixa de
-- ter DEFAULT 0 (0 nao existe em fornecedor e quebraria a FK).
CREATE TABLE public.pedido_compra (
    pedido_id         bigint           NOT NULL,
    data_pedido       date             NULL,
    item              integer          NOT NULL DEFAULT 0,
    produto_id        varchar(25)      NOT NULL DEFAULT '0',
    descricao_produto varchar(255)     NULL,
    ordem_compra      bigint           NOT NULL DEFAULT 0,
    qtde_pedida       double precision NULL,
    filial_id         integer          NULL,
    data_entrega      date             NULL,
    qtde_entregue     double precision NOT NULL DEFAULT 0,
    qtde_pendente     double precision NOT NULL DEFAULT 0,
    preco_compra      double precision NULL DEFAULT 0,
    fornecedor_id     integer          NULL,
    CONSTRAINT pedido_compra_pkey PRIMARY KEY (pedido_id, produto_id, item),
    CONSTRAINT pedido_compra_fornecedor_fk
        FOREIGN KEY (fornecedor_id) REFERENCES public.fornecedor (idfornecedor)
);

-- Ligacao pedido x entrada (ordem_compra + item + produto).
CREATE INDEX ix_pedido_compra_ordem
    ON public.pedido_compra (ordem_compra, item, produto_id);

-- Entradas: a PK citava 'ordem_compra', mas a coluna nao tinha sido declarada.
CREATE TABLE public.entradas_mercadoria (
    data_entrada      date             NULL,
    nro_nfe           varchar(255)     NOT NULL,
    item              integer          NOT NULL DEFAULT 0,
    produto_id        varchar(25)      NOT NULL DEFAULT '0',
    descricao_produto varchar(255)     NULL,
    ordem_compra      bigint           NOT NULL DEFAULT 0,
    qtde_recebida     double precision NULL,
    filial_id         integer          NULL,
    custo_unitario    numeric(12, 4)   NOT NULL DEFAULT 0,
    CONSTRAINT entradas_mercadoria_pkey
        PRIMARY KEY (ordem_compra, item, produto_id, nro_nfe)
);

-- Venda: estrutura original mantida; so os casts '::character varying' dos
-- defaults foram removidos por serem desnecessarios.
CREATE TABLE public.venda (
    venda_id       bigint           NOT NULL,
    data_emissao   date             NOT NULL,
    horariomov     varchar(8)       NOT NULL DEFAULT '00:00:00',
    produto_id     varchar(25)      NOT NULL DEFAULT '',
    qtde_vendida   double precision NULL,
    valor_unitario numeric(12, 4)   NOT NULL DEFAULT 0,
    filial_id      bigint           NOT NULL DEFAULT 1,
    item           integer          NOT NULL DEFAULT 0,
    unidade_medida varchar(3)       NULL,
    CONSTRAINT pk_consumo
        PRIMARY KEY (filial_id, venda_id, data_emissao, produto_id, item, horariomov)
);

CREATE INDEX ix_venda_data_emissao ON public.venda (data_emissao);
